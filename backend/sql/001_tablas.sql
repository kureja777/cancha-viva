begin;
create table public.canchas (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  deporte text not null check (deporte in ('Fútbol 7','Básquet','Vóley')),
  superficie text not null,
  precio_hora numeric(10,2) not null check (precio_hora > 0),
  activa boolean not null default true
);
create table public.clientes (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  nombre text not null check (length(trim(nombre)) >= 3)
);
create table public.reservas (
  id bigint generated by default as identity primary key,
  cancha_id bigint not null references public.canchas(id) on delete restrict,
  cliente_id bigint not null references public.clientes(id) on delete restrict,
  fecha date not null,
  hora integer not null check (hora between 7 and 21),
  estado text not null default 'confirmada'
    check (estado in ('confirmada','cancelada')),
  precio numeric(10,2) not null check (precio > 0),
  created_at timestamptz not null default now()
);
-- Un turno dura una hora. Una cancelación libera ese turno.
create unique index reservas_turno_unico
  on public.reservas(cancha_id,fecha,hora)
  where estado = 'confirmada';
create index reservas_cliente_idx on public.reservas(cliente_id);
alter table public.canchas enable row level security;
alter table public.clientes enable row level security;
alter table public.reservas enable row level security;
-- Las operaciones de escritura se hacen desde el backend de confianza.
revoke all on public.canchas,public.clientes,public.reservas
  from anon, authenticated;
commit;
